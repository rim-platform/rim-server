use chrono::{DateTime, Utc};

use crate::conversation::model::ConversationId;
use crate::incident::model::IncidentSeverity;
use crate::model_id;
use crate::server::model::ServerId;
use crate::user::model::UserId;

model_id!(IngestTokenId);

/// A per-workspace, per-channel token used to authenticate alert-ingestion webhooks
/// (`POST /api/hooks/alerts/*`). Mirrors the session/invite token pattern: only
/// [`Self::token_hash`] (SHA-256 hex) is ever persisted, never the raw token.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IngestToken {
    pub id: IngestTokenId,
    pub server_id: ServerId,
    /// Target channel: alerts ingested with this token create/update incidents here.
    pub conversation_id: ConversationId,
    /// The server-owner user who created the token. Also the acting principal for every
    /// incident this token ingests — see `IngestAlertCmd` in `rim_services::incident::command`.
    pub created_by: UserId,
    /// Human-readable label, e.g. "Prometheus prod".
    pub label: String,
    pub token_hash: String,
    /// Fallback severity applied when an ingested alert doesn't specify (or map to) one.
    pub severity_default: Option<IncidentSeverity>,
    pub created_at: DateTime<Utc>,
    pub revoked_at: Option<DateTime<Utc>>,
    pub last_used_at: Option<DateTime<Utc>>,
}

/// Fields required to persist a new ingest token. `token_hash` is the SHA-256 hex digest of
/// the raw token generated by `rim_auth::session_token::generate_ingest_token` — the raw token
/// itself is never passed to the repository layer.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewIngestToken {
    pub server_id: ServerId,
    pub conversation_id: ConversationId,
    pub created_by: UserId,
    pub label: String,
    pub token_hash: String,
    pub severity_default: Option<IncidentSeverity>,
}
